/* sw.js: lets the phone version work offline after the first visit.
   Network first: when online you always get the newest build; offline it uses the saved copy.
   (Only runs when the game is served from a website, never from a USB stick / file://.) */
const CACHE = 'papergame-v1';
self.addEventListener('install', () => self.skipWaiting());
self.addEventListener('activate', (e) => e.waitUntil(self.clients.claim()));
self.addEventListener('fetch', (e) => {
  if (e.request.method !== 'GET') return;
  e.respondWith(
    fetch(e.request).then((res) => {
      if (res && res.ok) { const copy = res.clone(); caches.open(CACHE).then((c) => c.put(e.request, copy)); }
      return res;
    }).catch(() => caches.match(e.request, { ignoreSearch: true }))
  );
});
